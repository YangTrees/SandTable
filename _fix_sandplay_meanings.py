def main() -> None:
    if len(CORES) != 500:
        raise SystemExit(f"释义映射数量异常：{len(CORES)}")

    data = json.loads(MAIN.read_text(encoding="utf-8"))
    items = data.get("items", [])
    ids = [item["id"] for item in items]
    if len(items) != 500 or len(set(ids)) != 500:
        raise SystemExit("主目录不是 500 条唯一 ID")

    missing = [item_id for item_id in ids if item_id not in CORES]
    extra = [item_id for item_id in CORES if item_id not in set(ids)]
    if missing or extra:
        raise SystemExit(f"映射不完整：missing={missing[:10]} extra={extra[:10]}")

    backup = MAIN.with_name("sandplay_miniatures_500.json.bak_keyword_20261120")
    if not backup.exists():
        shutil.copy2(MAIN, backup)

    for item in items:
        item["psychology_meaning"] = CORES[item["id"]] + SUFFIX

    data["meaning_revision"] = {
        "revised_at": "2026-11-20",
        "scope": "all_500_items",
        "method": "按沙具 ID 与具体名称逐条语义校正，不使用单字或子串关键词兜底",
        "revised_count": 500,
        "note": "释义为发展性沙盘中的探索性假设，需结合位置、组合与访谈核实，不作为诊断结论。",
    }
    MAIN.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # 同步生成批次和 Prompt 清单中的旧释义，保持同一 ID 全项目一致。
    synced = 0
    for path in SYNC_FILES:
        if not path.exists():
            continue
        payload = json.loads(path.read_text(encoding="utf-8"))
        rows = payload if isinstance(payload, list) else []
        for row in rows:
            if isinstance(row, dict) and row.get("id") in CORES:
                row["psychology_meaning"] = CORES[row["id"]] + SUFFIX
                synced += 1
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"main updated: {len(items)}")
    print(f"sync files: {len(SYNC_FILES)}")
    print(f"sync rows: {synced}")
    print(f"backup: {backup}")


if __name__ == "__main__":
    main()
